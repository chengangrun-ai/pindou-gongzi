// 解析为位数组，加载一次
const GLYPHS = {};
for (const [ch, rows] of Object.entries(GLYPH_ROWS)) {
  GLYPHS[ch] = rows.map(r => parseInt(r, 2));
}

export const FONT_W = 5;
export const FONT_H = 7;

export function normalizeText(text) {
  return String(text).toUpperCase().replace(/[×]/g, 'X').replace(/[·•]/g, '.');
}

export function hasGlyph(ch) {
  return Object.prototype.hasOwnProperty.call(GLYPHS, ch);
}

export function glyphOf(ch) {
  return GLYPHS[ch] || GLYPHS['?'];
}

// 文本像素宽度（scale 为整数放大倍数，字距 1 列）
export function measureText(text, scale) {
  const t = normalizeText(text);
  if (t.length === 0) return 0;
  return (t.length * (FONT_W + 1) - 1) * scale;
}

export function textHeight(scale) {
  return FONT_H * scale;
}

// 校验文本是否全部可渲染（用于 CLI / API 提前报错，保证两端行为一致）
export function unsupportedChars(text) {
  const t = normalizeText(text);
  const bad = new Set();
  for (const ch of t) if (!hasGlyph(ch)) bad.add(ch);
  return [...bad];
}